require("dotenv").config();

/* ================================================= */
/* ================= IMPORTS ======================= */
/* ================================================= */

const express = require("express");
const cors = require("cors");

/* ================================================= */
/* ================= DATABASE ====================== */
/* ================================================= */

require("./config/db");

/* ================================================= */
/* ================= ROUTES ======================== */
/* ================================================= */

const authRoutes = require(
  "./routes/authRoutes"
);

const userRoutes = require(
  "./routes/userRoutes"
);

const donationRoutes = require(
  "./routes/donationRoutes"
);

const paymentRoutes = require(
  "./routes/paymentRoutes"
);

const requestRoutes = require(
  "./routes/requestRoutes"
);

/* ================================================= */
/* ================= MIDDLEWARE ==================== */
/* ================================================= */

const {
  notFound,
  errorHandler,
} = require(
  "./middleware/errorMiddleware"
);

/* ================================================= */
/* ================= APP =========================== */
/* ================================================= */

const app = express();

/* ================================================= */
/* ================= CORS ========================== */
/* ================================================= */

app.use(

  cors({

    origin: [

      "http://localhost:3000",

      "http://localhost:3001",

      "http://127.0.0.1:3000",

      "http://127.0.0.1:3001",

    ],

    credentials: true,

  })

);

/* ================================================= */
/* ================= BODY PARSER =================== */
/* ================================================= */

app.use(express.json());

app.use(

  express.urlencoded({

    extended: true,

  })

);

/* ================================================= */
/* ================= LOGGER ======================== */
/* ================================================= */

app.use((req, res, next) => {

  console.log(
    `👉 ${req.method} ${req.url}`
  );

  next();

});

/* ================================================= */
/* ================= API ROUTES ==================== */
/* ================================================= */

/* ================= AUTH ================= */

app.use(
  "/api/auth",
  authRoutes
);

/* ================= USERS ================= */

app.use(
  "/api/users",
  userRoutes
);

/* ================= DONATIONS ================= */

app.use(
  "/api/donations",
  donationRoutes
);

/* ================= PAYMENTS ================= */

app.use(
  "/api/payments",
  paymentRoutes
);

/* ================= REQUESTS ================= */

app.use(
  "/api/requests",
  requestRoutes
);

/* ================================================= */
/* ================= HEALTH ROUTE ================== */
/* ================================================= */

app.get("/", (req, res) => {

  res.status(200).json({

    success: true,

    message:
      "TraceDonate API Running 🚀",

  });

});

/* ================================================= */
/* ================= ERROR HANDLER ================= */
/* ================================================= */

app.use(notFound);

app.use(errorHandler);

/* ================================================= */
/* ================= START SERVER ================== */
/* ================================================= */

const PORT =
  process.env.PORT || 5000;

app.listen(PORT, () => {

  console.log(
    `🚀 Server running on http://localhost:${PORT}`
  );

});